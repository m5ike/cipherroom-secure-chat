// Writes admin-ui/public/console-icons.js: the icons the operator console
// draws in its own chrome — the collapsed sidebar, the tabs of Functions,
// toolbars, the layout editor — as lucide's node data, and a tiny helper
// that turns a name into an <svg> (window.M5Icons.svg). Run after changing
// the list or upgrading lucide-react:
//
//   node script/gen-console-icons.mjs
//
// Icons: lucide (https://lucide.dev), ISC license.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ICONS = [
  // the shell
  "panel-left-close", "panel-left-open", "settings-2", "rotate-ccw", "sun-moon", "log-out", "key-round",
  // Functions' tabs and header
  "package", "workflow", "boxes", "calendar-clock", "webhook", "activity", "graduation-cap", "gauge", "power",
  "circle-check", "circle-x", "circle-alert", "timer", "hourglass", "pin", "pin-off", "chevron-down", "chevron-up",
  // the layout editor
  "lock", "lock-open", "grip-vertical", "move", "eye-off", "eye", "maximize-2", "minimize-2", "expand", "shrink",
  "align-start-vertical", "align-center-vertical", "align-end-vertical", "stretch-vertical", "wrap-text",
  "arrow-left", "arrow-right", "columns-2", "rows-2", "layout-grid", "square-dashed",
  // toolbars
  "play", "save", "upload", "download", "copy", "link-2", "refresh-cw", "trash-2", "plus", "search", "x",
  "external-link", "file-code", "code-xml", "undo-2", "redo-2", "list", "book-open", "send", "inbox", "zap", "shield-check",
  "radio", "clock", "filter", "bug", "square-terminal", "ellipsis", "chevrons-left", "chevrons-right",
];

const dir = join(import.meta.dirname, "..", "node_modules", "lucide-react", "dist", "esm", "icons");
const out = {};
const missing = [];
for (const name of [...new Set(ICONS)]) {
  let file = join(dir, `${name}.mjs`);
  if (!existsSync(file)) { missing.push(name); continue; }
  let src = readFileSync(file, "utf8");
  const reexport = src.match(/export \{ default \} from '\.\/([a-z0-9-]+)\.mjs'/);
  if (reexport) { file = join(dir, `${reexport[1]}.mjs`); src = readFileSync(file, "utf8"); }
  const match = src.match(/const __iconData = (\{[\s\S]*?\n\});/);
  if (!match) { missing.push(name); continue; }
  const data = Function(`"use strict"; return (${match[1]});`)();
  out[name] = data.node.map(([tag, attrs]) => [tag, Object.fromEntries(Object.entries(attrs).filter(([k]) => k !== "key"))]);
}
if (missing.length) { console.error(`not in this lucide-react: ${missing.join(", ")}`); process.exit(1); }

const pkg = JSON.parse(readFileSync(join(import.meta.dirname, "..", "node_modules", "lucide-react", "package.json"), "utf8"));
const body = `// GENERATED by script/gen-console-icons.mjs from lucide-react ${pkg.version} — do not edit.
// Icons: lucide (https://lucide.dev), ISC license.
//
// The operator console's own icons (6.1): window.M5Icons.svg(name, class)
// → an <svg> element (DOM nodes, never markup).
(() => {
  "use strict";
  const NS = "http://www.w3.org/2000/svg";
  const DATA = ${JSON.stringify(out)};
  function svg(name, cls = "ico") {
    const el = document.createElementNS(NS, "svg");
    const attrs = { width: 16, height: 16, viewBox: "0 0 24 24", fill: "none", stroke: "currentColor", "stroke-width": 2, "stroke-linecap": "round", "stroke-linejoin": "round", class: \`\${cls} ico-\${name}\`, "aria-hidden": "true", focusable: "false" };
    for (const [k, v] of Object.entries(attrs)) el.setAttribute(k, String(v));
    for (const [tag, a] of DATA[name] || DATA["circle-alert"]) {
      const child = document.createElementNS(NS, tag);
      for (const [k, v] of Object.entries(a)) child.setAttribute(k, String(v));
      el.append(child);
    }
    return el;
  }
  window.M5Icons = { svg, has: (name) => Object.prototype.hasOwnProperty.call(DATA, name), names: () => Object.keys(DATA) };
})();
`;
writeFileSync(join(import.meta.dirname, "..", "admin-ui", "public", "console-icons.js"), body);
console.log(`console-icons.js: ${Object.keys(out).length} icons`);
