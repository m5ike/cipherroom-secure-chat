// Writes server/functions/builtins/sources.ts from the real .js files in
// server/functions/builtins/src/<package>/ (5.2): the built-in packages
// (help, the demos and their netkit library) travel inside the server
// bundle. Run after changing a source: npm run gen:builtins
// (test/functions-builtins.test.ts fails when it is out of date).

import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "server", "functions", "builtins", "src");

export function builtinSources() {
  const out = {};
  for (const pkg of readdirSync(src).sort()) {
    if (!statSync(join(src, pkg)).isDirectory()) continue;
    out[pkg] = {};
    for (const f of readdirSync(join(src, pkg)).sort()) out[pkg][f] = readFileSync(join(src, pkg, f), "utf8");
  }
  return out;
}

export function renderSources(sources = builtinSources()) {
  return `// GENERATED by script/gen-builtins.mjs from server/functions/builtins/src — do not edit.\n// The built-in packages' files (5.2).\n\nexport const SOURCES: Record<string, Record<string, string>> = ${JSON.stringify(sources, null, 2)};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = join(root, "server", "functions", "builtins", "sources.ts");
  writeFileSync(file, renderSources());
  console.log(`wrote ${file}`);
}
