// Writes admin-ui/public/tsa-editor-icons.js: the icons of the TSA editor
// (6.9) — every tool of the palette (server/telephony/tsa/catalog.ts names a
// lucide icon per tool) and the editor's own chrome — as lucide's node data,
// with window.M5TsaIcons.svg(name, class) → an <svg> (DOM nodes, never
// markup). Kept apart from console-icons.js so the console's own set stays
// small. Run after adding a tool with a new icon or upgrading lucide-react:
//
//   node script/gen-tsa-editor-icons.mjs
//
// Icons: lucide (https://lucide.dev), ISC license.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ICONS = [
  // the palette (catalog.ts)
  "phone-incoming", "phone-off", "phone-forwarded", "pause", "grid-3x3", "volume-2", "play", "mic", "audio-lines",
  "radio-tower", "keyboard", "git-branch", "split", "repeat", "refresh-cw", "corner-down-right", "variable", "sigma",
  "type", "clock", "message-square-text", "message-circle", "globe", "square-function", "search", "key-round", "scroll-text",
  // the editor
  "x", "save", "check", "circle-check", "circle-alert", "triangle-alert", "circle-x", "undo-2", "redo-2", "cloud-upload",
  "download", "square", "phone", "phone-call", "mic-off", "volume-x", "zoom-in", "zoom-out", "scan", "network", "map",
  "hand", "mouse-pointer-2", "copy", "clipboard-paste", "trash-2", "plus", "minus", "chevron-down", "chevron-right",
  "info", "workflow", "list-tree", "bug", "shield-check", "history", "rotate-ccw", "send", "square-dashed", "arrow-left",
  "delete", "circle-help", "layers", "locate-fixed", "sliders-horizontal", "panel-right", "keyboard-music",
];

const dir = join(import.meta.dirname, "..", "node_modules", "lucide-react", "dist", "esm", "icons");
const out = {};
const missing = [];
for (const name of [...new Set(ICONS)]) {
  let file = join(dir, `${name}.mjs`);
  if (!existsSync(file)) { missing.push(name); continue; }
  let src = readFileSync(file, "utf8");
  const reexport = src.match(/export \{ default \} from '\.\/([a-z0-9-]+)\.mjs'/);
  if (reexport) { file = join(dir, `${reexport[1]}.mjs`); src = readFileSync(file, "utf8"); }
  const match = src.match(/const __iconData = (\{[\s\S]*?\n\});/);
  if (!match) { missing.push(name); continue; }
  const data = Function(`"use strict"; return (${match[1]});`)();
  out[name] = data.node.map(([tag, attrs]) => [tag, Object.fromEntries(Object.entries(attrs).filter(([k]) => k !== "key"))]);
}
if (missing.length) { console.error(`not in this lucide-react: ${missing.join(", ")}`); process.exit(1); }

const pkg = JSON.parse(readFileSync(join(import.meta.dirname, "..", "node_modules", "lucide-react", "package.json"), "utf8"));
const lines = Object.entries(out).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
const body = `// GENERATED by script/gen-tsa-editor-icons.mjs from lucide-react ${pkg.version} — do not edit.
// Icons: lucide (https://lucide.dev), ISC license.
//
// The TSA editor's icons (6.9): window.M5TsaIcons.svg(name, class) → an <svg>
// element (DOM nodes, never markup). Unknown names fall back to the console's
// own set (console-icons.js), then to a neutral circle.
(() => {
  "use strict";
  const NS = "http://www.w3.org/2000/svg";
  const DATA = {
${lines}
  };
  function svg(name, cls = "ico") {
    if (!Object.prototype.hasOwnProperty.call(DATA, name) && window.M5Icons && window.M5Icons.has && window.M5Icons.has(name)) return window.M5Icons.svg(name, cls);
    const el = document.createElementNS(NS, "svg");
    const attrs = { width: 16, height: 16, viewBox: "0 0 24 24", fill: "none", stroke: "currentColor", "stroke-width": 2, "stroke-linecap": "round", "stroke-linejoin": "round", class: \`\${cls} ico-\${name}\`, "aria-hidden": "true", focusable: "false" };
    for (const [k, v] of Object.entries(attrs)) el.setAttribute(k, String(v));
    for (const [tag, a] of DATA[name] || [["circle", { cx: "12", cy: "12", r: "9" }]]) {
      const child = document.createElementNS(NS, tag);
      for (const [k, v] of Object.entries(a)) child.setAttribute(k, String(v));
      el.append(child);
    }
    return el;
  }
  window.M5TsaIcons = { svg, has: (name) => Object.prototype.hasOwnProperty.call(DATA, name), names: () => Object.keys(DATA) };
})();
`;
writeFileSync(join(import.meta.dirname, "..", "admin-ui", "public", "tsa-editor-icons.js"), body);
console.log(`tsa-editor-icons.js: ${Object.keys(out).length} icons`);
